// ---------------------------------------------------------------------------
// Измерение близости смыслов
// ---------------------------------------------------------------------------
// Три уровня, от грубого к настоящему:
// 1. `themeSimilarity` — метки, проставленные вручную. Дёшево, предсказуемо,
//    но субъективно и не покрывает оттенки.
// 2. `lexicalSimilarity` — грубая лексическая близость: общие корни слов.
//    Даёт число без разметки, но ловит только совпадения слов, а не смысла.
// 3. Семантическая близость (будущее): векторное представление фразы и косинус
//    между векторами. Метрику нужно проверять на размеченной вручную выборке
//    пар «близко / далеко» и сравнивать с порядком, который ожидает человек;
//    модели должны укладываться в офлайн-размер игры.
// Пока адаптивное распределение использует веса давности; близость подключается
// параметром `similarity` и коэффициентом `boost` и по умолчанию выключена.

const STOP_WORDS = new Set(['и', 'а', 'но', 'не', 'ни', 'как', 'что', 'это', 'то', 'всё', 'все', 'всей', 'для', 'от', 'до', 'за', 'на', 'по', 'из', 'у', 'к', 'с', 'со', 'о', 'об', 'же', 'ли', 'бы', 'он', 'она', 'оно', 'они', 'его', 'её', 'их', 'нет', 'есть', 'там', 'тут', 'так', 'уже', 'ещё', 'вот', 'быть', 'том', 'тем', 'чем', 'при', 'про']);

function significantWords(text) {
  return (text.toLowerCase().match(/[\p{L}\p{N}]+/gu) ?? [])
    .filter(word => word.length > 2 && !STOP_WORDS.has(word))
    // Грубая нормализация: общий «корень» первых символов вместо морфологии.
    .map(word => word.slice(0, 5));
}

function jaccard(a, b) {
  if (!a.size || !b.size) return 0;
  let shared = 0;
  for (const item of a) if (b.has(item)) shared++;
  return shared / (a.size + b.size - shared);
}

export function lexicalSimilarity(a, b) {
  if (a === b) return 1;
  return jaccard(new Set(significantWords(text(a))), new Set(significantWords(text(b))));
}

export function themeSimilarity(a, b) {
  if (a === b) return 1;
  return jaccard(new Set(a?.themes ?? []), new Set(b?.themes ?? []));
}

function text(value) {
  return typeof value === 'string' ? value : (value?.text ?? '');
}

// ---------------------------------------------------------------------------
// Адаптивное распределение
// ---------------------------------------------------------------------------
// Вес цитаты лежит в диапазоне 0..1. Изначально все веса равны 1 — распределение
// равномерное. После выбора веса восстанавливаются наполовину (расстояние до 1
// делится пополам), а выбранная цитата обнуляется: предыдущая показанная получает
// 0,5, та, что перед ней, — 0,75 и так далее. Так недавно показанные цитаты
// уступают место остальным и постепенно возвращают вероятность.

// Доля пути, которую вес проходит за одно обращение к коллекции. 0,5 — половина
// расстояния до единицы: предыдущая цитата получает 0,5, следующая за ней 0,75.
export const DEFAULT_RECOVERY = 0.5;
export const DEFAULT_MEMORY = 12;

export function recoverWeights(weights, recovery = DEFAULT_RECOVERY) {
  const step = Math.min(Math.max(recovery, 0), 1);
  return weights.map(weight => {
    const value = Math.min(Math.max(weight, 0), 1);
    return value + (1 - value) * step;
  });
}

export function nextWeights(weights, index, recovery = DEFAULT_RECOVERY) {
  const recovered = recoverWeights(weights, recovery);
  if (index >= 0 && index < recovered.length) recovered[index] = 0;
  return recovered;
}

export function weightedPick(weights, random = Math.random) {
  const total = weights.reduce((sum, weight) => sum + Math.max(weight, 0), 0);
  // Если все веса обнулились (например, цитата одна), выбор снова равномерный.
  if (!(total > 0)) return Math.floor(random() * weights.length) % Math.max(weights.length, 1);
  let ticket = random() * total;
  for (let i = 0; i < weights.length; i++) {
    ticket -= Math.max(weights[i], 0);
    if (ticket < 0) return i;
  }
  return weights.length - 1;
}

export function createQuoteSelector({
  quotes = taoTeChing,
  random = Math.random,
  recovery = DEFAULT_RECOVERY,
  memory = DEFAULT_MEMORY,
  similarity = null,
  boost = 0,
  history = [],
} = {}) {
  if (!quotes.length) throw new RangeError('Коллекция цитат не может быть пустой');
  let weights = quotes.map(() => 1);
  let shown = [];

  const apply = id => {
    const index = quotes.findIndex(quote => quote.id === id);
    if (index < 0) return;
    weights = nextWeights(weights, index, recovery);
    shown = [...shown, id].slice(-Math.max(memory, 1));
  };
  for (const id of history) apply(id);

  return {
    get quotes() {
      return quotes;
    },
    get weights() {
      return [...weights];
    },
    get history() {
      return [...shown];
    },
    // Контекст — цитата, показанная ранее, или другая пара для сравнения.
    // Пока `similarity` не передана, распределение зависит только от давности.
    pick(context = null) {
      // Выбор идёт по текущим весам: только что показанная цитата имеет вес 0 и
      // повториться не может. Восстановление происходит в момент следующего
      // выбора, поэтому предыдущая цитата получает половинный вес.
      let blended = weights;
      if (similarity && boost > 0 && context) {
        const closeness = quotes.map(quote => Math.min(Math.max(similarity(context, quote), 0), 1));
        blended = weights.map((weight, i) => weight * (1 + boost * closeness[i]));
      }
      const index = weightedPick(blended, random);
      const quote = quotes[index];
      weights = nextWeights(weights, index, recovery);
      shown = [...shown, quote.id].slice(-Math.max(memory, 1));
      return quote;
    },
    reset() {
      weights = quotes.map(() => 1);
      shown = [];
    },
  };
}
